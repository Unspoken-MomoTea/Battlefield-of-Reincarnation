from pathlib import Path

root = Path(__file__).resolve().parents[1]
book = root / 'World Book'

def write(name, text):
    (book / name).write_text(text.strip() + '\n', encoding='utf-8', newline='\n')

def replace(name, old, new):
    text = (book / name).read_text(encoding='utf-8')
    assert text.count(old) == 1, (name, old[:60])
    write(name, text.replace(old, new))

