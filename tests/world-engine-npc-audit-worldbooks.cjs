const assert=require('node:assert/strict');
const {SamsaraWorldEngine:Engine}=require('../script/世界推进系统.js');
(async()=>{
  let stored=null;
  const host={localStorage:{getItem:()=>stored,setItem:(_,value)=>{stored=value;}},document:{},getCharWorldbookNames:()=>({primary:'测试书'}),getWorldbook:()=>['⚙️实体生成规则','NPC生成规则','状态协议','世界设定'].map((name,uid)=>({name,uid,content:name,enabled:true}))};
  const engine=new Engine(host);
  engine.render=()=>{};
  await engine.catalogue();
  const selected=()=>engine.bookCatalogue.filter(e=>engine.config.selectedEntries.includes(JSON.stringify([e.book,e.id]))).map(e=>e.title);
  assert.equal(selected().length,0);
  engine.config.selectedEntries.push(JSON.stringify(['测试书','3']));
  engine.setNpcBuildAuditEnabled(true);
  assert.equal(selected().length,4);
  engine.promptDraft={selectedEntries:[...engine.config.selectedEntries]};
  engine.setNpcBuildAuditEnabled(false);
  assert.deepEqual(selected(),['世界设定']);
  assert.deepEqual(engine.promptDraft.selectedEntries,engine.config.selectedEntries);
  const builtin=engine.getPromptDocuments().find(d=>d.id==='builtin-default');
  engine.setNpcBuildAuditEnabled(true);
  engine.applyPromptSettings({...builtin.settings,selectedEntries:[]});
  assert.equal(selected().length,3);
  engine.setNpcBuildAuditEnabled(false);
  engine.config.activationMode='force_selected';
  engine.config.selectedEntries=engine.bookCatalogue.map(e=>JSON.stringify([e.book,e.id]));
  const read=await engine.worldbook();
  assert.deepEqual(read.map(e=>e.名称),['世界设定']);
  const restored=new Engine(host);
  await restored.catalogue();
  assert.equal(restored.config.npcBuildAuditEnabled,false);
  assert.deepEqual(restored.config.selectedEntries,[JSON.stringify(['测试书','3'])]);
  console.log('NPC audit worldbook selection passed');
})().catch(error=>{console.error(error);process.exitCode=1;});
